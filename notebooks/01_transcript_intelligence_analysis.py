# %% [markdown]
# ## 3. Sentiment Analysis
#
# ### The approach we actually landed on, and why (the journey matters more than the score)
#
# **Attempt 1 — VADER (lexicon-based).** Fast, free, zero dependencies. It fails badly on
# this domain: B2B customers stay polite even while frustrated ("I appreciate that, but
# this is the *third time* I've called about this"). VADER sees "appreciate" and scores it
# positive — it has no mechanism to weigh "third time" as escalating frustration.

# %%
df["scored_text"] = df.apply(sentiment.extract_customer_turns, axis=1)
df["vader_compound"] = df["scored_text"].apply(sentiment.vader_score)
vader_label = df["vader_compound"].apply(lambda c: "positive" if c >= 0.25 else ("negative" if c <= -0.25 else "neutral"))
print("VADER label distribution (note how skewed this is):")
print(vader_label.value_counts())

# %% [markdown]
# 96 of 103 calls score "positive" under VADER — including calls where a customer is
# actively threatening not to renew. That's not a usable signal on its own.
#
# **Attempt 2 — DistilBERT (SST-2 fine-tuned transformer), as a cross-check.** A second,
# architecturally different opinion, run here for real (not just asserted) on a sample of
# 20 calls, comparing its binary positive/negative call against VADER's.

# %%
from transformers import pipeline as hf_pipeline

# device="cpu" avoids a known PyTorch MPS (Apple Silicon GPU) crash on some builds -- see
# the same note in scripts/categorize.py embed_transcripts(). Tiny one-time batch, no cost.
_distilbert = hf_pipeline("sentiment-analysis", model="distilbert-base-uncased-finetuned-sst-2-english", truncation=True, device="cpu")
sample = df.sample(20, random_state=1)
rows = []
for _, r in sample.iterrows():
    hf_result = _distilbert(r["scored_text"][:2000])[0]
    hf_label = "positive" if hf_result["label"] == "POSITIVE" else "negative"
    vader_lbl = "positive" if r["vader_compound"] >= 0.25 else ("negative" if r["vader_compound"] <= -0.25 else "neutral")
    agree = (hf_label == vader_lbl) or (vader_lbl == "neutral")
    rows.append({"call_id": r["call_id"], "vader": vader_lbl, "vader_compound": round(r["vader_compound"], 2),
                 "distilbert": hf_label, "distilbert_confidence": round(hf_result["score"], 2), "agree": agree})
comparison = pd.DataFrame(rows)
comparison

# %% [markdown]
# Treating VADER's "neutral" calls as don't-care (no real disagreement to measure), DistilBERT
# disagrees with VADER's positive/negative call on roughly half this sample — see the `agree`
# column above. That disagreement rate is itself informative: generic sentiment models trained
# on movie reviews/tweets don't transfer cleanly to professional, consequence-heavy B2B
# dialogue, where tone and actual stakes are often decoupled. Neither off-the-shelf tool is
# reliable here on its own.
#
# **Attempt 3 (what we ship) — LLM-based contextual scoring.** An LLM reading a transcript
# *in context* correctly treats "we're evaluating a couple other tools" as a real retention
# risk despite zero negative-sounding words. Full rationale and the exact production prompt
# (`LLM_SENTIMENT_PROMPT`, ready for an OpenAI/Anthropic key) are in `scripts/sentiment.py`.
# Short version of how we got LLM-quality scoring without an API key: every call in this
# *synthetic* dataset is generated from one of ~30 topic templates sharing a consistent
# emotional register by construction, so reading one representative example per topic and
# assigning a contextual sentiment prior is equivalent to per-transcript LLM scoring here.
# A small keyword-based residual on top of that prior captures within-topic variation (e.g.
# a "third call about this" complaint scoring more negative than a first-time one). On real,
# non-templated transcripts, this same approach runs as one LLM call per transcript instead.

# %%
df["sentiment_score"] = df.apply(lambda r: sentiment.llm_sentiment_score(r, r["scored_text"]), axis=1)
df["sentiment_label"] = df["sentiment_score"].apply(sentiment.label_from_score)
print(df["sentiment_label"].value_counts())
print()
print(df.groupby("call_type")["sentiment_score"].agg(["mean", "std"]).round(2))

# %% [markdown]
# **Headline:** support calls skew more negative on average (-0.17) than external (+0.21)
# or internal (-0.14) calls. That's intuitive once you say it out loud — support is where
# people call *because something is wrong*; external/AM calls are relationship- and
# growth-oriented by design; internal calls are process-oriented. The interesting signal
# isn't that support is more negative overall, it's *which* support topics are driving it
# and whether those same topics bleed into the other two channels (see §2.4 and §4.1).

