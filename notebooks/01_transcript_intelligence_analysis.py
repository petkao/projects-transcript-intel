# %% [markdown]
# ### 4.1 [Implemented] Cross-channel signal lag — how long did it take to notice and fix?
#
# **Who cares:** engineering leads and product managers. If the same issue is visible in
# support tickets weeks before it reaches a sprint board, that's a process gap, not a
# staffing gap — worth knowing before throwing headcount at "we're too slow to ship fixes."

# %%
milestones = {
    "First customer complaint (support)": "export_bug",
    "First internal awareness (eng triage)": "bug_triage_export_early",
    "Escalated internally (pulled forward)": "bug_triage_export_escalation",
    "First tied to renewal risk (external)": "renewal_risk_export_bug",
    "Fix shipped (internal)": "bug_triage_export_shipped",
    "Customer confirms resolved (support)": "export_bug_resolved",
}
timeline = pd.Series({k: df[df["synthetic_topic_label"] == v]["date"].min() for k, v in milestones.items()}).sort_values()
lags = timeline.diff().dt.days.fillna(0).astype(int)
for (label, date), lag in zip(timeline.items(), lags):
    print(f"{date.date()}  (+{lag:2d}d)  {label}")

print(f"\nTotal: {(timeline.iloc[-1] - timeline.iloc[0]).days} days from first customer complaint to confirmed resolution.")
print(f"{(timeline['Escalated internally (pulled forward)'] - timeline['First customer complaint (support)']).days} days "
      f"elapsed before the issue was treated as urgent internally — by which point it had already surfaced 3 separate times in support.")

# %% [markdown]
# **Recommendation:** surface a simple "this topic has appeared in N support calls in the
# last 30 days" counter directly on the engineering backlog, instead of relying on someone
# noticing the pattern by memory. The internal roadmap-planning call in this dataset
# independently arrives at the same conclusion ("support tickets and account escalations
# aren't visible to engineering in one place") — see cluster #6.

# %% [markdown]
# ### 4.2 [Implemented] Volume × negativity: where should engineering/support focus first?
#
# **Who cares:** support leaders and engineering leads prioritizing a backlog. A topic that's
# both common *and* negative is a better use of a sprint than a topic that's rare but severe,
# or common but merely neutral.

# %%
priority = df.groupby("category").agg(n=("call_id", "count"), mean_sentiment=("sentiment_score", "mean")).reset_index()
priority["priority_score"] = priority["n"] * -priority["mean_sentiment"].clip(upper=0)
priority = priority.sort_values("priority_score", ascending=False)

fig, ax = plt.subplots(figsize=(8, 5.5))
ax.scatter(priority["mean_sentiment"], priority["n"], s=priority["n"] * 15, alpha=0.6, c=priority["mean_sentiment"], cmap="RdYlGn")
for _, r in priority.iterrows():
    ax.annotate(r["category"], (r["mean_sentiment"], r["n"]), fontsize=7.5, xytext=(5, 3), textcoords="offset points")
ax.axvline(0, color="gray", linewidth=0.8, linestyle="--")
ax.set_xlabel("Mean sentiment (negative ← → positive)")
ax.set_ylabel("Call volume")
ax.set_title("Priority view: high volume + negative = fix first")
plt.tight_layout()
plt.savefig(f"{FIG_DIR}/04_priority_matrix.png", bbox_inches="tight")
plt.show()

priority[["category", "n", "mean_sentiment", "priority_score"]].round(2)

