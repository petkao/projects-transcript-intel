# %% [markdown]
# ## 2. Topic Categorization
#
# ### Approach, and why
#
# We went with a **hybrid: embeddings + unsupervised clustering + keyword/LLM labeling**,
# not pure rules and not pure zero-shot LLM classification. Reasoning:
#
# - **Pure rule-based (keyword matching)** requires knowing the categories up front, and
#   misses paraphrases. We don't know what's in this data yet — discovering the unexpected
#   (e.g. a bug that shows up in all three call types) is explicitly part of the task.
# - **Pure zero-shot LLM classification** (prompt an LLM with a fixed category list, per
#   transcript) is the strongest production option, but costs one API call per transcript,
#   requires pre-defining categories (circular, since discovering them is the point), and
#   isn't something we can run for free/reproducibly without an API key in this environment.
# - **Embeddings + clustering** is unsupervised — it finds structure without being told what
#   to look for. The tradeoff: raw clusters aren't human-readable, so we add a lightweight
#   labeling step (read top keywords + a representative example per cluster, assign a name).
#   That labeling step is the "hybrid" part, and in production is a natural fit for an LLM
#   call *per cluster* (~15 calls) instead of *per transcript* (~100+) — cheaper and the
#   categories still fall out of the data rather than being assumed.
#
# Full implementation is in `scripts/categorize.py` — this notebook calls into it.

# %% [markdown]
# ### 2.1 Embed, then pick K deliberately (not by just maximizing silhouette)
#
# On a small dataset, silhouette score keeps improving as K grows toward N (clusters
# shrink toward singletons) — that doesn't serve the actual goal of finding *meaningful,
# recurring* themes. Since this is a synthetic dataset, we have a `synthetic_topic_label`
# ground truth we can use as a secondary validation signal (**only for this validation
# step** — the clustering pipeline itself never sees this column). We pick the smallest K
# where cluster purity against that ground truth is high and no cluster degenerates to a
# singleton.

# %%
embeddings = categorize.embed_transcripts(df)
sweep = categorize.sweep_k(embeddings, validation_labels=df["synthetic_topic_label"], k_range=range(6, 21))
print(sweep.to_string(index=False))

fig, ax1 = plt.subplots(figsize=(7, 4))
ax1.plot(sweep["k"], sweep["silhouette"], marker="o", label="silhouette")
ax1.plot(sweep["k"], sweep["purity"], marker="s", label="purity vs. ground truth")
ax1.axvline(13, color="gray", linestyle="--", alpha=0.6, label="chosen K=13")
ax1.set_xlabel("K (number of clusters)")
ax1.legend()
ax1.set_title("Choosing K: silhouette keeps climbing, so we don't just maximize it")
plt.tight_layout()
plt.savefig(f"{FIG_DIR}/02_k_selection.png", bbox_inches="tight")
plt.show()

# %% [markdown]
# **K=13** chosen: purity reaches 0.72 against the fine-grained ground truth (0.76 for
# thematic groupings, see below) with no cluster smaller than n=3, while keeping clusters
# coarse enough to be useful to a leadership audience (13 themes, not 30+ micro-topics).

# %%
K = 13
df["cluster"] = categorize.fit_clusters(embeddings, K)
df["category"] = df["cluster"].map(lambda c: categorize.CLUSTER_LABELS.get(c, f"Cluster {c}"))

summary = categorize.cluster_summary(df)
summary

