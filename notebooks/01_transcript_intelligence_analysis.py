# %% [markdown]
# ### 4.3 [Implemented] Sentiment score ≠ churn risk — these need to be tracked separately
#
# **Who cares:** sales/CS leaders building a churn-risk dashboard. If you build "flag
# negative-sentiment calls" as your churn radar, you will miss the quietest, most dangerous
# signal: a customer who calmly mentions they're evaluating a competitor.

# %%
import re

RISK_PHRASES = ["evaluating", "considering not renewing", "competitor", "lumina",
                 "other tools", "other vendors", "won't renew", "not renew", "alternative"]
risk_re = [re.compile(p) for p in RISK_PHRASES]
df["churn_risk_flag"] = df["scored_text"].str.lower().apply(lambda t: any(r.search(t) for r in risk_re))

print(pd.crosstab(df["churn_risk_flag"], df["sentiment_label"], margins=True))
print()
flagged_not_negative = df[df["churn_risk_flag"] & (df["sentiment_label"] != "negative")]
print(f"{len(flagged_not_negative)} of {df['churn_risk_flag'].sum()} keyword-flagged 'risk' calls are NOT scored negative sentiment:")
print(flagged_not_negative[["call_id", "call_type", "synthetic_topic_label", "sentiment_label"]].to_string(index=False))

# %% [markdown]
# Two things are true at once here, and both matter:
#
# 1. **Sentiment alone misses risk.** A customer calmly evaluating "Lumina Analytics" on
#    price scores only mildly negative (-0.35) — far milder than an angry support call about
#    a solved bug. A sentiment-only alert would under-rank the more dangerous signal.
# 2. **Naive keyword risk-flagging over-fires.** 6 of the 15 keyword-flagged calls are
#    internal teams calmly discussing competitive *strategy* or a feature *launch* that
#    happens to mention a competitor by name — not customer-expressed risk at all. This is
#    the same lesson as sentiment: a keyword match isn't contextual judgment. In production,
#    "is this call a churn risk" deserves its own LLM-judged classification, separate from
#    sentiment, rather than either a sentiment threshold or a keyword list.

